"""Summarise evaluation runs for the report (no source text).

    python eval/summarize.py <run_id> [<run_id> ...] --out docs/results.md

Reads eval/runs/<run_id>/results.json and writes numbers and identifiers only. Fields that
hold document text (missed, false_positives, removed segment IDs) are never read, so the
output can be committed even though eval/runs/ is gitignored.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Annotated

import typer

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "eval" / "runs"

app = typer.Typer(add_completion=False)

HEADER = """# Evaluation results cited in the report

Generated by `eval/summarize.py` from `eval/runs/<run_id>/results.json` (that folder is
gitignored). Numbers and identifiers only; no document text. `–` means not recorded in that run.

- **Real meeting** (`fylkesutvalget_2026-09-29`): reproducible from a fresh clone with
  `make eval -Case fylkesutvalget_2026-09-29` and the meeting PDF (SHA-256 in the README); a
  fresh-clone replay on 29.10.2026 gave the same numbers. Gold is **provisional**: annotator A
  only, passages drafted by the coding agent and confirmed by a team member.
- **Synthetic case** (`algorithms_synthetic`): needs the copyrighted `algorithms.pdf`, so it
  cannot be reproduced from the repository. Its labels are provisional (drafted by the coding
  agent, not yet reviewed).
"""


def _f(x) -> str:
    if x is None:
        return "–"
    if isinstance(x, float):
        return f"{x:.2f}"
    if isinstance(x, list) and len(x) == 2:
        return f"{x[0]}/{x[1]}"
    return str(x)


def _row(cells) -> str:
    return "| " + " | ".join(_f(c) for c in cells) + " |"


def summarize_run(run_id: str, results: dict) -> str:
    """Markdown for one run, built from an allow-list of numeric fields."""
    models = ", ".join(f"{stage}={cfg.get('model')}"
                       + (f" ({cfg['strategy']})" if cfg.get("strategy") else "")
                       for stage, cfg in results.get("llm_config", {}).items())
    md = [f"## Run `{run_id}`", "",
          f"LLM mode: `{results.get('llm_mode')}` · models: {models}", ""]
    for case, styles in results.get("cases", {}).items():
        md += [f"### {case}", "",
               "| style | items | gold | found | selected | recall micro | recall macro "
               "| precision micro | F1 | S7 ceiling | skips | rejects | V1–V5 removed "
               "| LLM calls |",
               "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for style, res in styles.items():
            if style == "judge":
                continue
            a, s = res.get("aggregate", {}), res.get("summary", {})
            md.append(_row([style, a.get("items"), a.get("gold_passages"), a.get("found"),
                            a.get("selected"), a.get("recall_micro"), a.get("recall_macro"),
                            a.get("precision_micro"), a.get("f1_micro"),
                            a.get("candidate_recall"), a.get("skip_correct"),
                            a.get("reject_correct"),
                            [s.get("extracts_failed"), s.get("extracts_checked")]
                            if "extracts_checked" in s else None,
                            s.get("llm_calls")]))
        md.append("")
        for style, res in styles.items():
            if style == "judge":
                continue
            md += [f"**{style}, per item**", "",
                   "| item | expected | status | gold | found | selected | recall | precision "
                   "| removed |",
                   "|---|---|---|---|---|---|---|---|---|"]
            for it in res.get("items", []):
                md.append(_row([it.get("case_no"), it.get("expect"), it.get("status"),
                                it.get("n_gold"), it.get("n_found"), it.get("n_selected"),
                                it.get("recall"), it.get("precision"),
                                len(it["removed"]) if "removed" in it else None]))
            topics = res.get("aggregate", {}).get("found_by_topic")
            if topics:
                md += ["", "| subtopic | found / gold |", "|---|---|"]
                md += [_row([t, v]) for t, v in sorted(topics.items())]
            md.append("")
    rejected = results.get("rejected_input", [])
    if rejected:
        md += ["Rejected input (S0): " + ", ".join(
            f"{r['case']} {'✓' if r['rejected'] else '✗'}" for r in rejected), ""]
    return "\n".join(md)


@app.command()
def main(run_ids: list[str],
         out: Annotated[Path, typer.Option(help="Markdown file to write")]) -> None:
    parts = [HEADER]
    for run_id in run_ids:
        results = json.loads((RUNS / run_id / "results.json").read_text(encoding="utf-8"))
        parts.append(summarize_run(run_id, results))
    out.write_text("\n".join(parts), encoding="utf-8")
    typer.echo(f"wrote {out} ({len(run_ids)} runs)")


if __name__ == "__main__":
    app()
